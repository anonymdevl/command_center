"""Sales and receivables KPIs.

What is owed is the General Ledger's balance per customer (fact_party_balance), not
the open invoices' outstanding amounts: where payments are not matched to invoices the
two differ by millions. Both are here, and the reconciliation check (api/audit.py)
compares each with the business's ERPNext line by line.
"""

from command_center.kpi.registry import Kpi, register

