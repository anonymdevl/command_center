"""Buying and payables KPIs.

The mirror of the sales side, and deliberately so: what is owed to us and what we
owe are the same question asked in two directions, and a manager comparing them
should not have to allow for two different definitions of "overdue".
"""

from command_center.kpi.registry import Kpi, register

UNPAID = {"outstanding_amount": [">", 0], "src_docstatus": 1}
SUBMITTED = {"src_docstatus": 1}
SUPPLIERS = {"party_type": "Supplier"}
OWING = {**SUPPLIERS, "owed": [">", 0]}
IN_CREDIT = {**SUPPLIERS, "in_credit": [">", 0]}

register(
    # Owed by the ledger (15 Nov 2026), as on the sales side: Gigmann's open supplier
    # bills said GHS 15.54M while the General Ledger said GHS 2.61M, because GHS 10.18M
    # paid to suppliers was never matched to the bills it paid.
    Kpi(
        key="ap_total",
        label="Accounts Payable",
        fact="fact_party_balance",
        measure="owed",
        unit="currency",
        direction="higher_is_worse",
        filters=OWING,
        note="Supplier Ledger Balance, {ap_owing_count} suppliers; Purchase Invoice Outstanding {ap_open_invoices}",
        drill_filters=OWING,
        as_of_basis="data_horizon",
        components=("ap_over_90", "ap_inside_90", "ap_undated"),
    ),
    Kpi(
        key="ap_owing_count",
        label="Suppliers with a Payable",
        fact="fact_party_balance",
        measure="*",
        agg="count",
        unit="count",
        filters=OWING,
        note="{ap_total} Supplier Ledger Balance between them",
        drill_filters=OWING,
        as_of_basis="data_horizon",
    ),
    Kpi(
        key="ap_over_90",
        label="Payable Over 90 Days",
        fact="fact_party_balance",
        measure="d90_plus",
        unit="currency",
        direction="higher_is_worse",
        filters={**SUPPLIERS, "d90_plus": [">", 0]},
        note="{ap_over_90_share} of Accounts Payable, after unreconciled payments are set "
             "against the oldest Purchase Invoices",
        drill_filters={**SUPPLIERS, "d90_plus": [">", 0]},
        as_of_basis="data_horizon",
        subset_of="Accounts Payable",
        share_of="ap_total",
    ),
    Kpi(
        key="ap_inside_90",
        label="Within 90 Days",
        fact="fact_party_balance",
        measure="inside_90",
        unit="currency",
        filters={**SUPPLIERS, "inside_90": [">", 0]},
        note="{ap_inside_90_share} of what we owe",
        drill_filters={**SUPPLIERS, "inside_90": [">", 0]},
        as_of_basis="data_horizon",
        subset_of="Accounts Payable",
        share_of="ap_total",
    ),
    Kpi(
        key="ap_undated",
        label="Undated Ledger Balance",
        fact="fact_party_balance",
        measure="undated",
        unit="currency",
        direction="higher_is_worse",
        filters={**SUPPLIERS, "undated": [">", 0]},
        note="{ap_undated_share} of Accounts Payable: the Supplier Ledger holds more than open "
             "Purchase Invoices and opening balances explain",
        drill_filters={**SUPPLIERS, "undated": [">", 0]},
        as_of_basis="data_horizon",
        subset_of="Accounts Payable",
        share_of="ap_total",
    ),
    Kpi(
        key="ap_open_invoices",
        label="Purchase Invoice Outstanding",
        fact="fact_purchase_invoice",
        measure="outstanding_amount",
        unit="currency",
        filters=UNPAID,
        note="Outstanding Amount on {ap_count} unpaid Purchase Invoices",
        drill_filters=UNPAID,
        as_of_basis="data_horizon",
    ),
    Kpi(
        key="ap_count",
        label="Unpaid Purchase Invoices",
        fact="fact_purchase_invoice",
        measure="*",
        agg="count",
        unit="count",
        filters=UNPAID,
        note="Purchase Invoice Outstanding {ap_open_invoices}; Supplier Ledger Balance {ap_total}",
        drill_filters=UNPAID,
        as_of_basis="data_horizon",
    ),
    Kpi(
        key="ap_unmatched",
        label="Unreconciled Supplier Payments",
        fact="fact_party_balance",
        measure="unmatched_payments",
        unit="currency",
        direction="higher_is_worse",
        filters={**SUPPLIERS, "unmatched_payments": [">", 0]},
        note="across {ap_unmatched_count} unreconciled Payment Entries",
        drill_filters={**SUPPLIERS, "unmatched_payments": [">", 0]},
        as_of_basis="data_horizon",
    ),
    Kpi(
        key="ap_unmatched_count",
        label="Unreconciled Supplier Payments",
        fact="fact_party_balance",
        measure="unmatched_payment_count",
        unit="count",
        direction="higher_is_worse",
        filters={**SUPPLIERS, "unmatched_payments": [">", 0]},
        note="worth {ap_unmatched}",
        drill_filters={**SUPPLIERS, "unmatched_payments": [">", 0]},
        as_of_basis="data_horizon",
    ),
    Kpi(
        key="ap_in_credit",
        label="Supplier Advances",
        fact="fact_party_balance",
        measure="in_credit",
        unit="currency",
        direction="neutral",
        filters=IN_CREDIT,
        note="suppliers with a debit Supplier Ledger Balance",
        drill_filters=IN_CREDIT,
        as_of_basis="data_horizon",
    ),
    Kpi(
        key="spend_total",
        label="Purchase Invoiced",
        fact="fact_purchase_invoice_line",
        measure="base_net_amount",
        unit="currency",
        direction="neutral",
        filters=SUBMITTED,
        note="every submitted Purchase Invoice line",
        drill_filters=SUBMITTED,
        as_of_basis="data_horizon",
    ),
    Kpi(
        key="spend_lines",
        label="Purchase Invoice Lines",
        fact="fact_purchase_invoice_line",
        measure="*",
        agg="count",
        unit="count",
        filters=SUBMITTED,
        note="worth {spend_total}",
        drill_filters=SUBMITTED,
        as_of_basis="data_horizon",
    ),
    Kpi(
        key="supplier_billed",
        label="Purchase Invoices Grand Total",
        fact="fact_purchase_invoice",
        measure="base_grand_total",
        unit="currency",
        direction="neutral",
        filters=SUBMITTED,
        note="every submitted Purchase Invoice",
        drill_filters=SUBMITTED,
        as_of_basis="data_horizon",
    ),
    Kpi(
        # Named for what it measures. The first version of this was called
        # ap_settled_pct and labelled "Paid off" while computing the unpaid share --
        # the card would have shown a number that contradicted its own label, which
        # is worse than a wrong number because it is not obviously wrong.
        key="ap_unpaid_pct",
        label="Still Payable",
        fact="fact_party_balance",
        measure="*",
        agg="ratio",
        numerator="ap_total",
        denominator="supplier_billed",
        unit="percent",
        direction="higher_is_worse",
        note="of {supplier_billed} invoiced is still on the Supplier Ledger",
        as_of_basis="data_horizon",
        subset_of="all submitted Purchase Invoices",
    ),

    # Leaders (18 Oct 2026). Over all submitted supplier spend, not a top-14 extract.
    Kpi(
        key="supplier_top_share",
        label="Top Supplier",
        fact="fact_purchase_invoice_line",
        measure="base_net_amount",
        agg="top",
        group_by="supplier",
        as_share=True,
        unit="percent",
        direction="higher_is_worse",
        filters=SUBMITTED,
        note="{group}, of all Purchase Invoices",
        drill_filters=SUBMITTED,
        as_of_basis="data_horizon",
        subset_of="all submitted Purchase Invoices",
    ),
    Kpi(
        key="supplier_top2_share",
        label="Top Two Suppliers",
        fact="fact_purchase_invoice_line",
        measure="base_net_amount",
        agg="top",
        group_by="supplier",
        top_n=2,
        as_share=True,
        unit="percent",
        direction="higher_is_worse",
        filters=SUBMITTED,
        note="{group}",
        drill_filters=SUBMITTED,
        as_of_basis="data_horizon",
        subset_of="all submitted Purchase Invoices",
    ),
)
