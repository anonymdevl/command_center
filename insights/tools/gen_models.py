"""Generate insights/core/models_generated.py from the doctype JSON files.

    .venv-platform/bin/python -m insights.tools.gen_models

The doctypes under command_center/command_center/doctype stay the one definition of
the platform's tables: their fields, types, unique keys and permissions were designed
and tested there. This turns each into a Django model with the SAME table name
("tab<Doctype>") and the same column names, so every query the business logic makes
-- through insights.compat's frappe-shaped calls or the figure engine's PyPika
queries -- finds its data exactly where it always did.

Run it after changing a doctype JSON, then `manage.py makemigrations core`. Preflight
fails if the generated file is out of date.
"""

from __future__ import annotations

import glob
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
DOCTYPES = os.path.join(ROOT, "command_center", "command_center", "doctype")
OUT = os.path.join(ROOT, "insights", "core", "models_generated.py")

# Indexes the doctype controllers created in on_doctype_update (frappe.db.add_index).
EXTRA_INDEXES = {
    "Command Center Fact Sales Invoice Line": [["business_code", "item_group"],
                                               ["business_code", "posting_date"]],
    "Command Center Fact Stock Balance": [["business_code", "warehouse"],
                                          ["business_code", "item_group"]],
    "Command Center Fact Party Balance": [["business_code", "party_type", "party"]],
}

NO_COLUMN = {"Section Break", "Column Break", "Tab Break", "HTML", "Button", "Heading",
             "Password", "Fold", "Image"}


def class_name(doctype: str) -> str:
    return re.sub(r"[^0-9A-Za-z]", "", doctype.title())


def field_line(f: dict) -> str | None:
    ft, name = f["fieldtype"], f["fieldname"]
    if ft in NO_COLUMN:
        return None
    opts = ["null=True", "blank=True"]
    if f.get("unique"):
        opts.append("unique=True")
    if f.get("search_index"):
        opts.append("db_index=True")
    default = f.get("default")
    if ft in ("Data", "Link", "Select", "Dynamic Link", "Read Only", "Autocomplete",
              "Phone", "Color", "Rating", "Duration"):
        length = int(f.get("length") or 140)
        kind = f"models.CharField(max_length={length}, " + ", ".join(opts)
        if default not in (None, "") and not str(default).startswith(("eval:", "Today", "now")):
            kind += f", default={json.dumps(str(default))}"
        return f"    {name} = {kind})"
    if ft in ("Small Text", "Text", "Long Text", "Code", "Text Editor", "HTML Editor",
              "Markdown Editor", "JSON", "Table MultiSelect"):
        return f"    {name} = models.TextField({', '.join(opts)})"
    if ft == "Int":
        d = int(default) if str(default or "").lstrip("-").isdigit() else 0
        return f"    {name} = models.IntegerField({', '.join(opts)}, default={d})"
    if ft == "Check":
        d = 1 if str(default) == "1" else 0
        return f"    {name} = models.SmallIntegerField(default={d})"
    if ft in ("Float", "Currency", "Percent"):
        return (f"    {name} = models.DecimalField(max_digits=21, decimal_places=9, "
                f"{', '.join(opts)}, default=0)")
    if ft == "Date":
        return f"    {name} = models.DateField({', '.join(opts)})"
    if ft == "Datetime":
        return f"    {name} = models.DateTimeField({', '.join(opts)})"
    if ft == "Time":
        return f"    {name} = models.TimeField({', '.join(opts)})"
    raise SystemExit(f"{name}: no mapping for fieldtype {ft!r}")


def render() -> str:
    out = [
        '"""GENERATED by insights/tools/gen_models.py from the doctype JSON. Do not edit.',
        "",
        "Each model keeps its doctype's table and column names, so the business logic's",
        'queries are unchanged. Passwords are never columns: they live encrypted in',
        "core.Secret (insights.compat.secrets).",
        '"""',
        "",
        "from django.db import models",
        "",
        "",
        "class DocModel(models.Model):",
        '    """The columns every doctype row carries."""',
        "",
        "    name = models.CharField(primary_key=True, max_length=140)",
        "    creation = models.DateTimeField(null=True, blank=True)",
        "    modified = models.DateTimeField(null=True, blank=True, db_index=True)",
        "    modified_by = models.CharField(max_length=140, null=True, blank=True)",
        "    owner = models.CharField(max_length=140, null=True, blank=True)",
        "    docstatus = models.SmallIntegerField(default=0)",
        "    idx = models.IntegerField(default=0)",
        "",
        "    class Meta:",
        "        abstract = True",
        "",
        "    def __str__(self):",
        "        return self.name",
        "",
    ]
    registry = []
    for path in sorted(glob.glob(os.path.join(DOCTYPES, "*", "*.json"))):
        d = json.load(open(path))
        if d.get("doctype") != "DocType":
            continue
        dt, cls = d["name"], class_name(d["name"])
        out += ["", f"class {cls}(DocModel):"]
        seen = {"name", "creation", "modified", "modified_by", "owner", "docstatus", "idx"}
        for f in d.get("fields", []):
            if f["fieldname"] in seen:
                continue
            line = field_line(f)
            if line:
                out.append(line)
                seen.add(f["fieldname"])
        out += ["", "    class Meta:", f"        db_table = {json.dumps('tab' + dt)}",
                f"        verbose_name = {json.dumps(dt)}",
                f"        verbose_name_plural = {json.dumps(dt)}"]
        idx = EXTRA_INDEXES.get(dt)
        if idx:
            parts = ", ".join(
                f"models.Index(fields={cols!r}, name={json.dumps(('ix_' + cls[-14:] + '_' + '_'.join(c[:6] for c in cols))[:30])})"
                for cols in idx)
            out.append(f"        indexes = [{parts}]")
        out.append("")
        registry.append((dt, cls))
    out += ["", "# doctype name -> model, for insights.compat", "DOCTYPE_MODELS = {"]
    out += [f"    {json.dumps(dt)}: {cls}," for dt, cls in registry]
    out += ["}", ""]
    return "\n".join(out)


if __name__ == "__main__":
    text = render()
    if "--check" in sys.argv:
        current = open(OUT).read() if os.path.exists(OUT) else ""
        sys.exit(0 if current == text else 1)
    with open(OUT, "w") as fh:
        fh.write(text)
    print(f"wrote {OUT}")
